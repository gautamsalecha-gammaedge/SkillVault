const RTL_LANGUAGES = new Set(["ur-IN"]);

function t(key) {
  const lang = localStorage.getItem("sv_language") || "en-IN";
  return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || TRANSLATIONS["en-IN"][key] || key;
}

function applyLanguageDirection() {
  const lang = localStorage.getItem("sv_language") || "en-IN";
  document.body.setAttribute("dir", RTL_LANGUAGES.has(lang) ? "rtl" : "ltr");
}